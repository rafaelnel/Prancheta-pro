// Generate deterministic round-robin schedule for rounds 6 to 19
export function generateLeagueSchedule(): RoundFixture[] {
  const clubIds = INITIAL_CLUBS.map((c) => c.id);
  const fixtures: RoundFixture[] = [];

  // Circle method for 20 clubs
  const n = clubIds.length;
  const fixed = clubIds[0]; // atletico-paulistano
  const rotating = clubIds.slice(1);

  for (let round = 6; round <= 19; round++) {
    const shift = (round - 6) % (n - 1);
    const rotated = [
      ...rotating.slice(shift),
      ...rotating.slice(0, shift),
    ];
    const roundTeams = [fixed, ...rotated];

    for (let i = 0; i < n / 2; i++) {
      const t1 = roundTeams[i];
      const t2 = roundTeams[n - 1 - i];
      const isEvenRound = round % 2 === 0;
      const homeClubId = isEvenRound ? t1 : t2;
      const awayClubId = isEvenRound ? t2 : t1;
      const isUserMatch =
        homeClubId === USER_CLUB_ID || awayClubId === USER_CLUB_ID;

      fixtures.push({
        id: `r${round}-m${i + 1}`,
        roundNumber: round,
        homeClubId,
        awayClubId,
        homeGoals: null,
        awayGoals: null,
        played: false,
        isUserMatch,
      });
    }
  }

  // Ensure Round 6 user match is Atlético Paulistano (Home) vs EC Guanabara (Away) - top-of-the-table clash!
  const r6Fixtures = fixtures.filter((f) => f.roundNumber === 6);
  const r6NonOther = r6Fixtures.find((f) => f.isUserMatch);
  if (r6NonOther && r6NonOther.awayClubId !== 'esporte-clube-guanabara') {
    const gFixture = r6Fixtures.find(
      (f) =>
        f.homeClubId === 'esporte-clube-guanabara' ||
        f.awayClubId === 'esporte-clube-guanabara'
    );
    if (gFixture && gFixture.id !== r6NonOther.id) {
      const oldOpponent =
        r6NonOther.homeClubId === USER_CLUB_ID
          ? r6NonOther.awayClubId
          : r6NonOther.homeClubId;
      r6NonOther.homeClubId = USER_CLUB_ID;
      r6NonOther.awayClubId = 'esporte-clube-guanabara';
      if (gFixture.homeClubId === 'esporte-clube-guanabara') {
        gFixture.homeClubId = oldOpponent;
      } else {
        gFixture.awayClubId = oldOpponent;
      }
    }
  }

  return fixtures;
}

